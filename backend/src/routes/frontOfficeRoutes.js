const express = require('express')
const controller = require('../controllers/frontOfficeController')
const authenticate = require('../middleware/authenticate')
const authorize = require('../middleware/authorize')
const { requireBody, requireId } = require('../middleware/validate')

const router = express.Router()
router.use(authenticate, authorize('FRONT_OFFICE', 'ADMIN'))

router.get('/dashboard', controller.dashboard)

router.route('/guests')
  .get(controller.listGuests)
  .post(requireBody, controller.createGuest)
router.route('/guests/:id')
  .all(requireId)
  .get(controller.getGuest)
  .patch(requireBody, controller.updateGuest)
  .delete(controller.deleteGuest)

router.route('/reservations')
  .get(controller.listReservations)
  .post(requireBody, controller.createReservation)
router.route('/reservations/:id')
  .all(requireId)
  .get(controller.getReservation)
  .patch(requireBody, controller.updateReservation)
  .delete(controller.cancelReservation)
router.post('/reservations/:id/check-in', requireId, controller.checkIn)
router.post('/reservations/:id/check-out', requireId, controller.checkOut)

router.get('/rooms', controller.listRooms)
router.get('/rooms/:id', requireId, controller.getRoom)
router.patch('/rooms/:id/status', requireId, requireBody, controller.updateRoom)

router.route('/guest-requests')
  .get(controller.listRequests)
  .post(requireBody, controller.createRequest)
router.patch('/guest-requests/:id', requireId, requireBody, controller.updateRequest)

router.route('/invoices')
  .get(controller.listInvoices)
  .post(requireBody, controller.createInvoice)
router.route('/invoices/:id')
  .all(requireId)
  .get(controller.getInvoice)
  .patch(requireBody, controller.updateInvoice)
router.route('/invoices/:id/payments')
  .all(requireId)
  .get(controller.listPayments)
  .post(requireBody, controller.createPayment)
router.route('/payments/:id')
  .all(requireId)
  .get(controller.getPayment)
  .patch(requireBody, controller.updatePayment)

module.exports = router

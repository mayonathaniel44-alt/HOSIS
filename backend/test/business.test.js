const {test}=require('node:test');
const assert=require('node:assert/strict');
const express=require('express');
const Database=require('better-sqlite3');
const {mkdtempSync,rmSync}=require('node:fs');
const {tmpdir}=require('node:os');
const {join}=require('node:path');
const {createSuperAdmin,createAuthRouter}=require('../src/auth');
const {createBusinessRouter,today}=require('../src/business');

test('persistent pipeline, permissions, atomic conversion, finance, archive and recovery',async()=>{
  const dir=mkdtempSync(join(tmpdir(),'hosis-business-'));
  const path=join(dir,'test.db');
  let db=new Database(path),server;
  async function start(){const app=express();app.use(express.json({limit:'10mb'}));app.use('/api/auth',createAuthRouter(db));app.use('/api/business',createBusinessRouter(db));server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));return `http://127.0.0.1:${server.address().port}`;}
  createSuperAdmin(db,'Test-only-password!');
  let base=await start();
  async function login(username,password){const res=await fetch(`${base}/api/auth/login`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username,password})});assert.equal(res.status,200);return res.headers.get('set-cookie').split(';')[0];}
  let admin=await login('superadmin','Test-only-password!');
  async function call(path,method='GET',body,cookie=admin,status=200){const res=await fetch(`${base}/api/business${path}`,{method,headers:{'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},body:body?JSON.stringify(body):undefined});const data=await res.json();assert.equal(res.status,status,JSON.stringify(data));return data;}
  const create=(kind,data,cookie=admin)=>call(`/records/${kind}`,'POST',data,cookie,201);
  const act=(r,action,values={},cookie=admin,status=200)=>call(`/records/${r.id}/action`,'POST',{version:r.version,action,...values},cookie,status);
  const day=today(),future=new Date(Date.parse(day)+86400000*10).toISOString().slice(0,10),end=new Date(Date.parse(day)+86400000*12).toISOString().slice(0,10);
  try{
    await call('/workspace','GET',null,null,401);
    await call('/users','POST',{username:'manager',name:'Test Manager',role:'Manager',password:'Manager-test-password!'},admin,201);
    const staffUser=await call('/users','POST',{username:'staff',name:'Test Staff',role:'Sales Staff',password:'Staff-test-password!'},admin,201);
    const manager=await login('manager','Manager-test-password!'),staff=await login('staff','Staff-test-password!');
    await call('/users','GET',null,manager,403);
    await call('/users','POST',{username:'unauthorized',name:'Blocked',role:'Sales Staff',password:'Staff-test-password!'},manager,403);
    await call('/backup','GET',null,manager,403);
    for(const phone of ['abc','091712345678','0917123'])await call('/records/clients','POST',{name:'Invalid '+phone,contact:'Test',phone},admin,400);
    for(const phone of ['09171234567','+639171234567','639171234567'])await create('clients',{name:'Valid '+phone,contact:'Test',phone});
    const campaignData={name:'Test campaign',channel:'Website',start:day,end,budget:1000,spent:100,status:'Active'};
    await call('/records/campaigns','POST',campaignData,staff,403);
    await call('/records/campaigns','POST',{...campaignData,end:'2020-01-01'},admin,400);
    const campaign=await create('campaigns',campaignData);
    const promo=await create('promotions',{name:'Ten percent',campaignId:campaign.id,start:day,end,discount:10,terms:'Test eligibility'});
    await act(promo,'approve',{},admin,403);
    const approved=await act(promo,'approve',{},manager);
    const inquiry=await create('inquiries',{name:'Test Guest',subject:'Room',date:day,source:'Website',campaignId:campaign.id,status:'New',email:'guest@example.test',followUp:day},staff);
    await call(`/records/${inquiry.id}`,'PUT',{...inquiry,version:99},staff,409);
    const lead=await act(inquiry,'convert',{},staff);
    const freshInquiry=(await call('/workspace')).records.find(r=>r.id===inquiry.id);
    await act(freshInquiry,'convert',{},staff,409);
    const q=await create('quotations',{name:'Deluxe room',leadId:lead.id,date:day,checkIn:future,checkOut:end,validUntil:future,gross:1000,promotionId:approved.id},staff);
    assert.equal(q.amount,900);
    await act(q,'confirm',{reservationRef:'RSV-TEST'},staff,400);
    const sale=await act(q,'confirm',{reservationRef:'RSV-TEST',availabilityConfirmed:true},staff);
    assert.equal(sale.amount,900);
    const accepted=(await call('/workspace')).records.find(r=>r.id===q.id);
    await act(accepted,'confirm',{reservationRef:'RSV-TEST',availabilityConfirmed:true},staff,400);
    await act(sale,'payment',{type:'Receipt',amount:100,date:day,externalReference:'FIN-1'},staff,403);
    await act(sale,'payment',{type:'Receipt',amount:1000,date:day,externalReference:'FIN-1'},manager,400);
    const receipt=await act(sale,'payment',{type:'Receipt',amount:500,date:day,externalReference:'FIN-1'},manager);assert.match(receipt.reference,/^REC-\d{8}-\d{6}$/);assert.equal(receipt.externalReference,'FIN-1');
    let freshSale=(await call('/workspace')).records.find(r=>r.id===sale.id);
    await act(freshSale,'payment',{type:'Receipt',amount:100,date:day,externalReference:'FIN-1'},manager,409);
    await act(freshSale,'payment',{type:'Refund',amount:501,date:day,externalReference:'REF-1'},manager,400);
    freshSale=await act(freshSale,'cancel',{reason:'Customer cancellation'},manager);
    assert.equal(freshSale.cancellationFee,90);assert.equal(freshSale.refundableAtCancellation,410);
    await act(freshSale,'payment',{type:'Receipt',amount:10,date:day,externalReference:'FIN-2'},manager,400);
    await act(freshSale,'payment',{type:'Refund',amount:500,date:day,externalReference:'REF-1'},manager,400);
    await act(freshSale,'payment',{type:'Refund',amount:410,date:day,externalReference:'REF-1'},manager);
    const feeLead=await create('leads',{name:'Partial payment guest',date:day,subject:'Room',source:'Website',status:'Qualified'});
    const feeQuote=await create('quotations',{name:'Partial booking',leadId:feeLead.id,date:day,checkIn:future,checkOut:end,validUntil:future,gross:1000});
    let feeSale=await act(feeQuote,'confirm',{reservationRef:'RSV-FEE',availabilityConfirmed:true});
    await act(feeSale,'payment',{type:'Receipt',amount:50,date:day});
    feeSale=(await call('/workspace')).records.find(r=>r.id===feeSale.id);
    feeSale=await act(feeSale,'cancel',{reason:'Partial booking cancelled'});
    assert.equal(feeSale.cancellationFee,100);assert.equal(feeSale.refundableAtCancellation,0);
    await act(feeSale,'payment',{type:'Refund',amount:1,date:day},admin,400);
    await act(feeSale,'payment',{type:'Receipt',amount:50,date:day});
    await call(`/records/${campaign.id}/archive`,'POST',{version:campaign.version},admin,400);
    const client=await create('clients',{name:'Test Company',contact:'Test Contact',email:'company@example.test'});
    await call(`/records/${client.id}/archive`,'POST',{version:client.version});
    let archived=(await call('/workspace')).records.find(r=>r.id===client.id);assert.equal(archived.archived,true);
    await call(`/records/${client.id}/archive`,'POST',{version:archived.version});
    const trash=await create('clients',{name:'Trash example',contact:'Test Contact'});
    await call('/records/'+trash.id+'/delete','POST',{version:trash.version},staff,403);
    await call('/records/'+trash.id+'/delete','POST',{version:trash.version});
    assert.equal((await call('/workspace')).records.find(r=>r.id===trash.id).archived,true);
    await call('/records/'+sale.id+'/delete','POST',{version:((await call('/workspace')).records.find(r=>r.id===sale.id)).version},admin,400);
    const adminNotifications=await call('/notifications');const staffNotifications=await call('/notifications','GET',null,staff);
    assert.ok(adminNotifications.unread>0);assert.ok(staffNotifications.unread>0);
    await call('/notifications/read','POST',{id:adminNotifications.items[0].id},staff);
    assert.equal((await call('/notifications')).unread,adminNotifications.unread);
    await call('/notifications/read','POST',{},staff);
    assert.equal((await call('/notifications','GET',null,staff)).unread,0);
    assert.equal((await call('/notifications')).unread,adminNotifications.unread);
    const snapshot=await call('/backup');
    await call('/backup','GET',null,staff,403);
    const n=snapshot.records.length;
    await call('/restore','POST',{confirm:'RESTORE',snapshot:{...snapshot,records:[...snapshot.records,snapshot.records[0]]}},admin,400);
    assert.equal((await call('/workspace')).records.length,n);
    await create('clients',{name:'After backup',contact:'Test Contact'});
    await call('/restore','POST',{confirm:'RESTORE',snapshot});
    assert.equal((await call('/workspace')).records.length,n);
    assert.equal((await call('/recovery')).length,1);
    assert.equal((await call('/recovery/'+(await call('/recovery'))[0].id)).records.length,n+1);
    const bad=structuredClone(snapshot);bad.records.find(r=>r.kind==='payments').saleId='MISSING';
    await call('/restore','POST',{confirm:'RESTORE',snapshot:bad},admin,400);
    assert.equal((await call('/workspace')).records.length,n);
    assert.ok((await call('/audit')).some(r=>r.action==='restore backup'));
    const malformed=structuredClone(snapshot);delete malformed.records.find(r=>r.kind==='sales').amount;
    await call('/restore','POST',{confirm:'RESTORE',snapshot:malformed},admin,400);
    assert.equal((await call('/workspace')).records.length,n);
    await call('/audit','GET',null,staff,403);
    const otherManager=await login('manager','Manager-test-password!');
    await call('/password','POST',{currentPassword:'wrong',password:'New-manager-test-password!',confirmPassword:'New-manager-test-password!'},manager,403);
    await call('/password','POST',{currentPassword:'Manager-test-password!',password:'New-manager-test-password!',confirmPassword:'New-manager-test-password!'},manager);
    await call('/workspace','GET',null,otherManager,401);
    await call('/workspace','GET',null,manager);
    await call(`/users/${staffUser.id}/access`,'POST',{role:'Disabled'});
    await call('/workspace','GET',null,staff,401);
    // Stop and reopen the actual SQLite file, not just the same connection.
    await new Promise(r=>server.close(r));db.close();db=new Database(path);base=await start();
    admin=await login('superadmin','Test-only-password!');
    assert.equal((await call('/workspace')).records.length,n);
    const persisted=(await call('/workspace')).records.find(r=>r.id===sale.id);assert.equal(persisted.status,'Cancelled');
    const examples=await call('/examples','POST',{});assert.equal(examples.added,14);
    const demo=(await call('/workspace')).records.filter(r=>r.isExample);
    for(const kind of ['campaigns','inquiries','leads','clients','promotions','quotations','sales','payments'])assert.ok(demo.filter(r=>r.kind===kind).length>=1&&demo.filter(r=>r.kind===kind).length<=2);
    assert.equal((await call('/examples','POST',{})).added,0);
    const sampleSale=demo.find(r=>r.kind==='sales');
    const generated=await act(sampleSale,'payment',{type:'Receipt',amount:10,date:day,reference:'FORGED-REFERENCE'});
    assert.match(generated.reference,/^REC-\d{8}-\d{6}$/);assert.notEqual(generated.reference,'FORGED-REFERENCE');assert.equal(generated.externalReference,'');
    const references=(await call('/workspace')).records.filter(r=>r.kind==='payments').map(r=>r.reference);
    assert.equal(new Set(references).size,references.length);
    const demoBackup=await call('/backup');await call('/restore','POST',{confirm:'RESTORE',snapshot:demoBackup});
    const starter=await call('/starter','POST',{});assert.ok(starter.added>=19);
    const initial=(await call('/workspace')).records;
    assert.ok(initial.some(r=>!r.archived&&r.name==='Summer Getaway'&&r.budget===25000));
    assert.ok(initial.some(r=>!r.archived&&r.kind==='sales'&&r.name==='Angela Cruz'&&r.amount===8500));
    assert.ok(initial.some(r=>r.id===sale.id&&r.status==='Cancelled'));
    assert.equal((await call('/starter','POST',{})).added,0);
    const initialBackup=await call('/backup');await call('/restore','POST',{confirm:'RESTORE',snapshot:initialBackup});
  }finally{await new Promise(r=>server.close(r));db.close();rmSync(dir,{recursive:true,force:true});}
});
